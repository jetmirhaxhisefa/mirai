import { summaryOf } from './summary.js';
import { checkIds, linkLinesOf } from './rules.js';
import { byKey, capsOf, coverage, graphProblems, prdItems, ticketsOf } from './graph.js';

// The epic's own lint (unit 33; design/01 §5, §12a; Jet's decisions 2026-11-20). The epic is the
// page you approve a ticket set from. What the generic rules can't say:
// - the four generated sections (Tickets, Dependencies, Coverage, Design decisions) are exactly
//   what `mirai epic render` writes from the ticket files and the PRD; a hand edit inside them,
//   or a ticket changed since, is drift (decision 2);
// - "Decisions for you" lists, by ticket key, every ticket that needs your call: `risk: high`,
//   `e2e: true`, a `tdd` or `tests` override; and the release mode when it's `together`
//   (decision 4);
// - "## Release" names the frontmatter's release mode;
// - the "Design:" line is there on `full`, and on `standard` when a ticket names an ADR
//   (decision 5); its links resolving is the link rules' check;
// - the epic's own non-goals don't reuse a number the PRD or the brief already has;
// - the ticket graph lint (src/lint/graph.js).

export const GENERATED = Object.freeze(['Tickets', 'Dependencies', 'Coverage', 'Design decisions']);
export const START = '<!-- generated by mirai epic render: edit the tickets, then run it again -->';
export const END = '<!-- end of the generated part -->';
const RELEASES = ['per-ticket', 'together'];

// The tickets of this epic as the lint and the command read them: { status: 'ok', tickets, all }
// or { status: 'unavailable' } when the text was linted alone. Each ticket: { path, value, doc,
// title, ownAcs }.
export function ticketSet(doc, ctx) {
  const read = ctx.readTickets ? ctx.readTickets() : { status: 'unavailable' };
  if (read.status !== 'ok') return read;
  const all = read.all.map((t) => withDetail(t, ctx.registry));
  return { status: 'ok', all, tickets: ticketsOf(all, doc.value.id) };
}

function withDetail(t, registry) {
  const def = registry?.documentTypes?.[t.value.type];
  const title = t.doc.scan.headings.find((h) => h.level === 1)?.text ?? '';
  let ownAcs = 0;
  if (def && typeof t.value.id === 'string') {
    // The ticket's own ACs (AC-<key>.n), counted as the ticket's own lint counts them.
    ownAcs = checkIds(t.doc, def, () => {}, null).get('AC')?.size ?? 0;
  }
  return { ...t, title, ownAcs };
}

export function checkEpic(doc, def, ctx, add) {
  const { scan, value } = doc;
  const title = scan.headings.find((h) => h.level === 1);
  const top = { line: title?.line ?? doc.bodyLine, column: 1 };
  const h2 = (name) => scan.headings.find((h) => h.level === 2 && h.text === name);
  const ticketsAt = h2('Tickets') ? { line: h2('Tickets').line, column: 1 } : top;
  const up = ctx.upstream?.status === 'ok' ? ctx.upstream : null;
  const set = ticketSet(doc, ctx);
  const tickets = set.status === 'ok' ? set.tickets : null;

  // ---- The release mode ----------------------------------------------------------------------
  const release = h2('Release');
  if (release && RELEASES.includes(value.release)) {
    const text = sectionText(scan, release);
    const named = RELEASES.filter((r) => new RegExp(`(?<![\\w-])${r}(?![\\w-])`).test(text));
    if (!named.includes(value.release)) add({ code: 'epic-release', line: release.line, column: 1, reason: `"## Release" doesn't name the epic's release mode, ${value.release}`, hint: `say "${value.release}" and why; together is only with a reason (design/01 §12a)` });
  }

  // ---- The Design: line ----------------------------------------------------------------------
  const lines = linkLinesOf(scan, def);
  if (!lines.some((l) => l.link.label === 'Design')) {
    const adr = (tickets ?? []).find((t) => Array.isArray(t.value.governed_by) && t.value.governed_by.length);
    const why = value.track === 'full' ? 'on the full track the epic links its design' : adr ? `${adr.value.id} names ${adr.value.governed_by[0]} in governed_by, so the epic links its design` : null;
    if (why) add({ code: 'upstream-link', line: lines.at(-1)?.line ?? top.line, column: 1, reason: `${why}: add "Design: [<its title>](<file>.md)" under the PRD line`, hint: 'link the HLD and LLDs, comma-separated: Design: [HLD](hld.md), [LLD for reminders](lld-reminders.md)' });
  }

  // ---- Decisions for you (decision 4) ----------------------------------------------------------
  const s = summaryOf(scan);
  const decisions = s?.parts.find((p) => p.heading.text === 'Decisions for you');
  const decisionText = (decisions?.lines ?? []).filter((l) => l.kind === 'text').map((l) => l.visible ?? l.text).join('\n');
  const at = { line: decisions?.heading.line ?? s?.h2.line ?? top.line, column: 1 };
  if (value.release === 'together' && !/\btogether\b/i.test(decisionText)) add({ code: 'epic-decision', ...at, reason: 'the release mode is together, but "Decisions for you" doesn\'t ask you', hint: 'add an item: release together, the reason, and the alternative (per-ticket, the default)' });
  for (const t of tickets ?? []) {
    const key = String(t.value.id);
    const needs = [
      t.value.risk === 'high' ? 'risk: high' : null,
      t.value.e2e === true ? 'e2e: true' : null,
      typeof t.value.tdd === 'string' ? `tdd: ${t.value.tdd}` : null,
      typeof t.value.tests === 'string' ? `tests: ${t.value.tests}` : null,
    ].filter(Boolean);
    if (needs.length && !mentions(decisionText, key)) add({ code: 'epic-decision', ...at, reason: `${key} is ${needs.join(', ')}, but "Decisions for you" doesn't list it`, hint: `add an item naming ${key} with a one-line reason, so you decide it at the ticket gate` });
  }

  // ---- The epic's own non-goals carry on after the PRD's and the brief's -----------------------
  if (up) {
    const highest = Math.max(0, ...(up.doc.text.match(/\bNG-[0-9]+\b/g) ?? []).map((id) => Number(id.slice(3))));
    const notIn = h2('Not in this epic');
    const next = notIn && scan.headings.find((h) => h.line > notIn.line && h.level <= 2);
    for (const l of scan.lines) {
      if (!notIn || l.line <= notIn.line || (next && l.line >= next.line) || l.kind !== 'text') continue;
      const m = /^ *(?:[-*+]|[0-9]{1,9}[.)])[ \t]+(?:\*\*)?(NG-([0-9]+))(?:\*\*)?(?::|[ \t]+—[ \t])/.exec(l.text);
      if (m && Number(m[2]) <= highest) add({ code: 'epic-numbering', line: l.line, column: 1, reason: `${m[1]} is defined here, but the PRD and its brief already use NG numbers up to NG-${highest}`, hint: `cite theirs as they are; number the epic's own from NG-${highest + 1}` });
    }
  }

  if (!tickets) return; // linted alone: the graph and the generated parts need the tickets
  const items = up ? prdItems(up) : null;
  for (const p of graphProblems({ epicId: String(value.id), track: value.track, tickets, all: set.all, items, caps: capsOf(ctx.project?.limits) })) add({ ...p, ...ticketsAt });

  // ---- The generated sections (decision 2) -----------------------------------------------------
  if (!up) return; // the coverage needs the PRD
  const want = renderSections({ track: value.track, tickets, items });
  const fileLines = (doc.text ?? '').replace(/\r\n/g, '\n').split('\n');
  const hint = `run: mirai epic render ${ctx.file ?? '<epic file>'}`;
  for (const name of GENERATED) {
    const h = h2(name);
    if (!h) continue; // the section rules report it
    const end = scan.headings.find((x) => x.line > h.line && x.level <= 2)?.line ?? fileLines.length + 1;
    const have = trimBlank(fileLines.slice(h.line, end - 1).map((l) => l.replace(/[ \t]+$/, '')));
    if (have.join('\n') === want.get(name).join('\n')) continue;
    const marked = have[0] === START && have.at(-1) === END;
    add({ code: 'epic-generated', line: h.line, column: 1, reason: marked ? `"## ${name}" doesn't match the ticket files and the PRD (edited by hand, or a ticket changed since it was rendered)` : `"## ${name}" isn't the generated part`, hint });
  }
}

const mentions = (text, key) => new RegExp(`(?<![\\w.-])${key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\w]|[.-][\\w])`, 'i').test(text);

function sectionText(scan, h) {
  const next = scan.headings.find((x) => x.line > h.line && x.level <= 2);
  return scan.lines.filter((l) => l.line > h.line && (!next || l.line < next.line) && l.kind === 'text').map((l) => l.visible ?? l.text).join('\n');
}

function trimBlank(lines) {
  let a = 0;
  let b = lines.length;
  while (a < b && lines[a].trim() === '') a++;
  while (b > a && lines[b - 1].trim() === '') b--;
  return lines.slice(a, b);
}

// ---- Rendering (decision 2) ---------------------------------------------------------------------

const cell = (text) => String(text).replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\s+/g, ' ').trim();
const ids = (v) => (Array.isArray(v) && v.length ? v.filter((x) => typeof x === 'string').map(cell).join(', ') : '—');

// The four sections' text, each as lines: the start marker, the body, the end marker. `items`:
// the PRD's coverable IDs (graph.js prdItems).
export function renderSections({ track, tickets, items }) {
  const out = new Map();
  const key = (t) => cell(t.value.id);
  const sorted = [...tickets].sort((a, b) => byKey(String(a.value.id), String(b.value.id)));

  out.set('Tickets', [
    '| Key | Title | Size | Risk | After | FRs | ACs | ADRs |',
    '|---|---|---|---|---|---|---|---|',
    ...sorted.map((t) => `| [${key(t)}](${t.path}) | ${cell(t.title) || '—'} | ${cell(t.value.size ?? '—')} | ${cell(t.value.risk ?? '—')} | ${ids(t.value.after)} | ${ids(t.value.covers_fr)} | ${ids(t.value.covers_ac)} | ${ids(t.value.governed_by)} |`),
  ]);

  const node = new Map(sorted.map((t, i) => [String(t.value.id).toLowerCase(), `t${i + 1}`]));
  const edges = [];
  for (const t of sorted) {
    for (const a of Array.isArray(t.value.after) ? t.value.after : []) {
      const from = typeof a === 'string' ? node.get(a.toLowerCase()) : null;
      if (from && from !== node.get(String(t.value.id).toLowerCase())) edges.push(`  ${from} --> ${node.get(String(t.value.id).toLowerCase())}`);
    }
  }
  out.set('Dependencies', [
    '```mermaid',
    'flowchart LR',
    ...sorted.map((t) => `  ${node.get(String(t.value.id).toLowerCase())}["${key(t)} (${cell(t.value.size ?? '?')})"]`),
    ...edges,
    '```',
  ]);

  const covered = coverage(sorted);
  // On full, each epic covers its own FRs: its table lists those. Otherwise every PRD ID.
  const rows = (items ?? []).filter((i) => track !== 'full' || covered.has(i.id));
  out.set('Coverage', [
    '| ID | Group | Tickets |',
    '|---|---|---|',
    ...rows.map((i) => `| ${i.id} | ${cell(i.group)} | ${covered.get(i.id)?.map(cell).join(', ') ?? '—'} |`),
  ]);

  const adrs = new Map();
  for (const t of sorted) {
    for (const a of Array.isArray(t.value.governed_by) ? t.value.governed_by : []) {
      if (typeof a !== 'string') continue;
      if (!adrs.has(a)) adrs.set(a, []);
      adrs.get(a).push(key(t));
    }
  }
  out.set('Design decisions', adrs.size
    ? [...adrs.keys()].sort(byKey).map((a) => `- [${cell(a)}](adr/${cell(a)}.md): governs ${adrs.get(a).join(', ')}.`)
    : ['None — no ticket names an ADR in `governed_by`.']);

  for (const [name, body] of out) out.set(name, [START, ...body, END]);
  return out;
}

// The epic's text with the four sections rewritten, everything else as it was. Returns { text,
// missing: [section names not found] }.
export function renderEpic(text, sections) {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const lines = text.split(/\r?\n/);
  const missing = [];
  let fence = null;
  const h2At = [];
  lines.forEach((l, i) => {
    const f = /^ {0,3}(`{3,}|~{3,})/.exec(l);
    if (f) {
      if (!fence) fence = f[1];
      else if (l.trim().startsWith(fence)) fence = null;
      return;
    }
    if (!fence && /^ {0,3}#{1,2}[ \t]/.test(l)) h2At.push({ i, level: /^ {0,3}(#{1,2})/.exec(l)[1].length, text: l.replace(/^ {0,3}#{1,2}[ \t]+/, '').replace(/[ \t]+#*[ \t]*$/, '').trim() });
  });
  for (const name of GENERATED) if (!h2At.some((h) => h.level === 2 && h.text === name)) missing.push(name);
  // One pass: a generated section's heading is kept, and everything up to the next heading of
  // level 1 or 2 is replaced by its rendered part.
  const result = [];
  let skipping = false;
  let current = null;
  const heads = new Map(h2At.map((h) => [h.i, h]));
  for (let i = 0; i < lines.length; i++) {
    const h = heads.get(i);
    if (h) {
      if (skipping) result.push('');
      skipping = false;
      current = h.level === 2 && GENERATED.includes(h.text) ? h.text : null;
      result.push(lines[i]);
      if (current) {
        result.push('', ...sections.get(current));
        skipping = true;
      }
      continue;
    }
    if (!skipping) result.push(lines[i]);
  }
  if (skipping) result.push('');
  return { text: result.join(eol), missing };
}
